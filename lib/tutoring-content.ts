function getExamName(serviceName: string) {
  const examLevel = getExamLevel(serviceName);
  return examLevel === "검정고시" ? "검정고시" : `${examLevel} 검정고시`;
}

function getExamSubjectKey(serviceName: string): ExamSubjectKey {
  return getSubjectKey(serviceName) ?? "general";
}

function applySingleTemplate(text: string, replacements: Record<string, string>) {
  return Object.entries(replacements).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, value),
    text,
  );
}

function hasSubjectTermMismatch(text: string, subjectKey: SubjectKey) {
  if (subjectKey !== "english" && /파닉스|영작|구문|듣기/u.test(text)) {
    return true;
  }

  if (subjectKey !== "math" && subjectKey !== "science" && /연산|공식|계산|풀이 전략|풀이 과정/u.test(text)) {
    return true;
  }

  if (subjectKey !== "koreanHistory" && /연표|시대 흐름/u.test(text)) {
    return true;
  }

  if (subjectKey !== "korean" && /문학|비문학/u.test(text)) {
    return true;
  }

  return false;
}

function getOnlineSafeContext(
  text: string | undefined,
  subjectKey: SubjectKey,
  fallback: string,
) {
  const value = text?.trim();

  if (!value || hasSubjectTermMismatch(value, subjectKey)) {
    return fallback;
  }

  return value;
}

